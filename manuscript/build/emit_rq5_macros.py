#!/usr/bin/env python3
"""Validate a compliant RQ5 result and emit all LaTeX macros from raw runs."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ARMS = {"A0": "AZero", "A1": "AOne", "A2": "ATwo"}
RATES = {5.0: "Five", 25.0: "TwentyFive", 100.0: "Hundred"}


def mean(values):
    return sum(values) / len(values)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("input")
    parser.add_argument("--macros", required=True)
    parser.add_argument("--summary", required=True)
    parser.add_argument("--code-root", default=None)
    args = parser.parse_args()
    doc = json.loads(Path(args.input).read_text())
    if doc.get("status") != "PASS" or doc.get("protocol") != "czta-v9-replacement-open-loop-v2":
        raise SystemExit("Not a compliant v2 protocol result")
    documents = doc["documents"]
    if sorted(d["arm"] for d in documents) != ["A0", "A1", "A2"]:
        raise SystemExit("Need A0, A1, A2")
    if len({d["implementation"]["code_manifest_sha256"] for d in documents}) != 1:
        raise SystemExit("Code hash differs between arms")
    if any(d["implementation"]["implementation"] != "v9-replacement-2" for d in documents):
        raise SystemExit("Wrong implementation identifier")

    summary = {}
    for d in documents:
        arm = d["arm"]
        if d.get("reps") != 3 or d.get("status") != "PASS" or d.get("errors"):
            raise SystemExit(f"Invalid arm {arm}")
        for rate in RATES:
            runs = [r for r in d["runs"] if r["rate_req_s"] == rate]
            if sorted(r["rep"] for r in runs) != [1, 2, 3]:
                raise SystemExit(f"Missing restarted repetition for {arm} at {rate}")
            if any(r.get("errors") for r in runs):
                raise SystemExit(f"Measured errors for {arm} at {rate}")
            summary[f"{arm}_{rate}"] = {
                "p50": mean([r["p50_ms"] for r in runs]),
                "p95": mean([r["p95_ms"] for r in runs]),
                "measured_requests": sum(r["measured_requests"] for r in runs),
            }
    for rate in RATES:
        summary[f"overhead_{rate}"] = 100.0 * (summary[f"A2_{rate}"]["p50"] - summary[f"A0_{rate}"]["p50"]) / summary[f"A0_{rate}"]["p50"]

    rla = documents[2]["rla"]
    if rla["iterations"] != 1000 or rla["errors"]:
        raise SystemExit("RLA validation failed")
    trusted_lines = None
    if args.code_root:
        root = Path(args.code_root)
        trusted_lines = sum(len(p.read_text().splitlines()) for folder in ("czta_gateway", "czta_ref") for p in (root / folder).glob("*.py"))

    macros = []

    def M(name, value):
        macros.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    for arm, arm_name in ARMS.items():
        for rate, rate_name in RATES.items():
            values = summary[f"{arm}_{rate}"]
            M(f"RqFive{arm_name}{rate_name}Cell", f"{values['p50']:.2f}/{values['p95']:.2f}")
            M(f"RqFive{arm_name}{rate_name}Median", f"{values['p50']:.2f}")
            M(f"RqFive{arm_name}{rate_name}Tail", f"{values['p95']:.2f}")
            M(f"RqFive{arm_name}{rate_name}N", values["measured_requests"])
    for rate, rate_name in RATES.items():
        M(f"RqFiveOverhead{rate_name}", f"{summary[f'overhead_{rate}']:.1f}")
    M("RqFiveOverheadRange", f"{min(summary[f'overhead_{r}'] for r in RATES):.1f}--{max(summary[f'overhead_{r}'] for r in RATES):.1f}\\,\\%")
    M("RqFiveRlaSignCell", f"{rla['sign_p50_ms']:.2f}/{rla['sign_p95_ms']:.2f}")
    M("RqFiveRlaVerifyCell", f"{rla['verify_p50_ms']:.2f}/{rla['verify_p95_ms']:.2f}")
    M("RqFiveRlaIterations", rla["iterations"])
    M("RqFiveCodeHashShort", documents[0]["implementation"]["code_manifest_sha256"][:12])
    if trusted_lines is not None:
        M("RqFiveTrustedLines", trusted_lines)

    Path(args.macros).write_text("% AUTO-GENERATED by build/emit_rq5_macros.py from compliant restarted MCP runs.\n" + "\n".join(macros) + "\n")
    Path(args.summary).write_text(json.dumps({"summary": summary, "rla": rla, "trusted_lines": trusted_lines}, indent=2) + "\n")
    print(json.dumps({"macros": len(macros), "overhead": {r: summary[f"overhead_{r}"] for r in RATES}, "trusted_lines": trusted_lines}, indent=2))


if __name__ == "__main__":
    main()
